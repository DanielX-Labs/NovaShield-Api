import { env } from "../../config/env.js";
import type { EmailProvider } from "./email.types.js";

// Load only the selected provider; SES does not initialize Brevo credentials.
async function getProvider(): Promise<EmailProvider> {
  switch (env.EMAIL_PROVIDER) {
    case "brevo":
      return (await import("./brevoSmtp.provider.js")).brevoSmtpProvider;
    case "ses":
      throw new Error("Amazon SES provider has not been configured yet.");
    default:
      throw new Error("Unsupported email provider.");
  }
}

export async function sendPasswordResetOtpEmail(
  email: string,
  otp: string,
  expiresAt: Date = new Date(Date.now() + env.PASSWORD_RESET_OTP_TTL_MINUTES * 60_000),
  challengeId?: string,
): Promise<void> {
  // Restrict template input to the numeric code generated by the OTP service.
  if (!/^\d{6}$/u.test(otp)) {
    throw new Error("Reset code must contain six digits.");
  }
  if (!challengeId || !/^[a-f0-9]{24}$/u.test(challengeId)) {
    throw new Error("Reset challenge identifier is required.");
  }
  const provider = await getProvider();
  // Absolute expiry remains truthful after queue delays and retries.
  const expiry = expiresAt.toISOString();
  await provider.send({
    to: email,
    subject: "Reset your NovaPay password",
    text:
      `Your password reset code is ${otp}. It expires at ${expiry} (UTC). ` +
      `Your reset challenge ID is ${challengeId}. Enter both values to reset your password. ` +
      "Never share this code. If you did not request it, ignore this email.",
    html: `
      <div>
        <h2>Reset your password</h2>
        <p>Your password reset code is <strong>${otp}</strong>.</p>
        <p>Reset challenge ID: <code>${challengeId}</code></p>
        <p>This code expires at ${expiry} (UTC).</p>
        <p>Never share this code. If you did not request it, ignore this email.</p>
      </div>
    `,
  });
}

export async function sendPasswordChangedEmail(email: string): Promise<void> {
  // A security notification contains no credentials, tokens or verification codes.
  const provider = await getProvider();
  await provider.send({
    to: email,
    subject: "Your NovaPay password was changed",
    text:
      "Your password was changed and all sessions were signed out. " +
      "If you did not make this change, reset your password and contact support.",
    html: `
      <div>
        <h2>Your password was changed</h2>
        <p>All sessions were signed out.</p>
        <p>If you did not make this change, reset your password and contact support.</p>
      </div>
    `,
  });
}

export async function sendVerificationOtpEmail(
  email: string,
  otp: string,
  expiresAt: Date = new Date(Date.now() + env.OTP_TTL_MINUTES * 60_000),
  challengeId?: string,
): Promise<void> {
  // Only numeric OTPs can enter the HTML template.
  if (!/^\d{6}$/u.test(otp)) {
    throw new Error("Verification code must contain six digits.");
  }
  if (!challengeId || !/^[a-f0-9]{24}$/u.test(challengeId)) {
    throw new Error("Verification challenge identifier is required.");
  }
  const provider = await getProvider();

  // Include both plain text and HTML for mail-client compatibility.
  await provider.send({
    to: email,
    subject: "Verify your NovaPay email address",
    text:
      `Your NovaPay verification code is ${otp}. ` +
      `Your verification challenge ID is ${challengeId}. ` +
      "Enter both and choose your password to finish creating your account. " +
      `It expires at ${expiresAt.toISOString()} (UTC). ` +
      "Never share this code with anyone. " +
      "If you did not request this code, you can ignore this email.",
    html: `
      <div>
        <h2>Verify your email</h2>
        <p>Verification challenge ID: <code>${challengeId}</code></p>
        <p>Enter this ID and code, then choose your password to complete registration.</p>
        <p>Use the following verification code:</p>
        <p style="font-size: 28px; font-weight: bold; letter-spacing: 6px;">
          ${otp}
        </p>
        <p>This code expires at ${expiresAt.toISOString()} (UTC).</p>
        <p>Never share this code with anyone.</p>
        <p>If you did not request this code, you can ignore this email.</p>
      </div>
    `,
  });
}
